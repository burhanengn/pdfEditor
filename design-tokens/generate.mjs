function escapeTsSingleQuote(val) {
  return val.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function buildTsI18n(i18n) {
  const keys = Object.keys(i18n);
  const enLines = keys.map(
    (k) => `  '${escapeTsSingleQuote(k)}': '${escapeTsSingleQuote(i18n[k].en)}',`,
  );
  const trLines = keys.map(
    (k) => `  '${escapeTsSingleQuote(k)}': '${escapeTsSingleQuote(i18n[k].tr)}',`,
  );

  return [
    '// AUTO-GENERATED by design-tokens/generate.mjs — edit design-tokens/i18n.json',
    "export type SupportedLocale = 'en' | 'tr';",
    '',
    "export const SUPPORTED_LOCALES: SupportedLocale[] = ['en', 'tr'];",
    '',
    'export const enDictionary = {',
    ...enLines,
    '} as const;',
    '',
    'export type TranslationKey = keyof typeof enDictionary;',
    '',
    'export const trDictionary: Record<TranslationKey, string> = {',
    ...trLines,
    '};',
    '',
    'export const dictionaries: Record<SupportedLocale, Record<TranslationKey, string>> = {',
    '  en: enDictionary,',
    '  tr: trDictionary,',
    '};',
    '',
  ].join('\n');
}

