function escapeDartString(val) {
  return val.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$');
}

function buildDartL10n(i18n) {
  const keys = Object.keys(i18n);
  const enEntries = keys.map((k) => `    '${k}': '${escapeDartString(i18n[k].en)}',`);
  const trEntries = keys.map((k) => `    '${k}': '${escapeDartString(i18n[k].tr)}',`);

  return [
    '// AUTO-GENERATED by design-tokens/generate.mjs — edit design-tokens/i18n.json',
    'enum GpLocale { en, tr }',
    '',
    'class GpL10n {',
    '  const GpL10n(this.locale);',
    '  final GpLocale locale;',
    '',
    '  static GpLocale detectFromLanguageCode(String languageCode) {',
    "    return languageCode.toLowerCase().startsWith('tr') ? GpLocale.tr : GpLocale.en;",
    '  }',
    '',
    '  static const Map<String, String> _en = {',
    ...enEntries,
    '  };',
    '',
    '  static const Map<String, String> _tr = {',
    ...trEntries,
    '  };',
    '',
    '  String t(String key, [Map<String, Object?> params = const {}]) {',
    '    final dict = locale == GpLocale.tr ? _tr : _en;',
    '    var out = dict[key] ?? _en[key] ?? key;',
    '    for (final entry in params.entries) {',
    "      out = out.replaceAll('{\${entry.key}}', '\${entry.value ?? \"\"}');",
    '    }',
    '    return out;',
    '  }',
    '}',
    '',
  ].join('\n');
}

function buildArb(locale, i18n) {
  const obj = { '@@locale': locale };
  for (const [k, v] of Object.entries(i18n)) {
    const arbKey = k.replace(/[^a-zA-Z0-9]+([a-zA-Z0-9])/g, (_, ch) => ch.toUpperCase());
    obj[arbKey] = v[locale] ?? v.en;
  }
  return JSON.stringify(obj, null, 2) + '\n';
}

function writeOrCheck(filePath, content, checkOnly) {
  if (checkOnly) {
    if (!fs.existsSync(filePath) || fs.readFileSync(filePath, 'utf-8') !== content) {
      console.error(`Out of sync generated file: ${filePath}`);
      return false;
    }
    return true;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf-8');
  return true;
}

const tokens = JSON.parse(fs.readFileSync(TOKENS_PATH, 'utf-8'));
const i18n = JSON.parse(fs.readFileSync(I18N_PATH, 'utf-8'));
const checkOnly = process.argv.includes('--check');

const outputs = [
  [OUT_CSS_PATH, buildCss(tokens)],
  [OUT_TS_I18N_PATH, buildTsI18n(i18n)],
  [OUT_DART_TOKENS_PATH, buildDartTokens(tokens)],
  [OUT_DART_L10N_PATH, buildDartL10n(i18n)],
  [OUT_ARB_EN_PATH, buildArb('en', i18n)],
  [OUT_ARB_TR_PATH, buildArb('tr', i18n)],
];

let allOk = true;
for (const [targetPath, content] of outputs) {
  if (!writeOrCheck(targetPath, content, checkOnly)) {
    allOk = false;
  }
}

if (!allOk) {
  process.exit(1);
}
console.log(checkOnly ? 'design-tokens up to date.' : `Generated ${outputs.length} token & i18n files.`);
